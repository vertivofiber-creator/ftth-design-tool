export function buildPorts(
  inputCount: number,
  outputCount: number,
  prefixIn = 'IN',
  prefixOut = 'OUT',
  connectorType = 'SC/APC',
  defaultTxPowerDbm?: number
): { inputPorts: ComponentPort[]; outputPorts: ComponentPort[] } {
  const inputPorts: ComponentPort[] = Array.from({ length: inputCount }, (_, idx) => ({
    id: `in-${idx + 1}`,
    label: `${prefixIn}-${idx + 1}`,
    direction: 'in',
    index: idx,
    connectorType,
  }));
  const outputPorts: ComponentPort[] = Array.from({ length: outputCount }, (_, idx) => ({
    id: `out-${idx + 1}`,
    label: `${prefixOut}-${idx + 1}`,
    direction: 'out',
    index: idx,
    connectorType,
    ...(defaultTxPowerDbm !== undefined ? { txPowerDbm: defaultTxPowerDbm } : {}),
  }));
  return { inputPorts, outputPorts };
}

